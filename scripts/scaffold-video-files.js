import fs from "node:fs";
import path from "node:path";

const publicDir = path.resolve("public");
const workDir = path.join(publicDir, "work");

// Minimal valid MP4 header byte sequence (FTYP box)
const minimalMp4Buffer = Buffer.from([
  0x00, 0x00, 0x00, 0x1c, 0x66, 0x74, 0x79, 0x70, // ftyp box length & type
  0x69, 0x73, 0x6f, 0x6d, 0x00, 0x00, 0x02, 0x00, // isom brand
  0x69, 0x73, 0x6f, 0x6d, 0x69, 0x73, 0x6f, 0x32,
  0x61, 0x76, 0x63, 0x31, 0x6d, 0x70, 0x34, 0x31,
  0x00, 0x00, 0x00, 0x08, 0x66, 0x72, 0x65, 0x65, // free box
]);

// Minimal valid WEBM header byte sequence (EBML header)
const minimalWebmBuffer = Buffer.from([
  0x1a, 0x45, 0xdf, 0xa3, 0x9f, 0x42, 0x86, 0x81,
  0x01, 0x42, 0xf7, 0x81, 0x01, 0x42, 0xf2, 0x81,
  0x04, 0x42, 0xf3, 0x81, 0x08, 0x42, 0x82, 0x84,
  0x77, 0x65, 0x62, 0x6d, 0x42, 0x87, 0x81, 0x04,
  0x42, 0x85, 0x81, 0x02,
]);

const videoFiles = [
  { path: path.join(publicDir, "hero.mp4"), type: "mp4" },
  { path: path.join(publicDir, "hero.webm"), type: "webm" },
  { path: path.join(workDir, "lead-response.mp4"), type: "mp4" },
  { path: path.join(workDir, "lead-response.webm"), type: "webm" },
  { path: path.join(workDir, "ops-dispatch.mp4"), type: "mp4" },
  { path: path.join(workDir, "ops-dispatch.webm"), type: "webm" },
];

fs.mkdirSync(workDir, { recursive: true });

for (const v of videoFiles) {
  const buf = v.type === "mp4" ? minimalMp4Buffer : minimalWebmBuffer;
  fs.writeFileSync(v.path, buf);
  console.log(`Scaffolded ${v.path}`);
}
